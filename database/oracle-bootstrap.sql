  CREATE OR REPLACE EDITIONABLE PROCEDURE "SP_COMPLETE_SALE" (
    P_SALE_ID IN NUMBER
)
AS
    V_STATUS VARCHAR2(20);
    V_ORDER_DISCOUNT NUMBER;
    V_COUNT NUMBER;
    V_SUBTOTAL NUMBER;
    V_GRAND_TOTAL NUMBER;
BEGIN

    BEGIN

        SELECT
            STATUS,
            DISCOUNT
        INTO
            V_STATUS,
            V_ORDER_DISCOUNT
        FROM SALE
        WHERE SALE_ID = P_SALE_ID
        FOR UPDATE;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                -20209,
                'Sale does not exist.'
            );
    END;


    IF V_STATUS <> 'PENDING' THEN
        RAISE_APPLICATION_ERROR(
            -20210,
            'Sale is not pending.'
        );
    END IF;


    SELECT COUNT(*)
    INTO V_COUNT
    FROM SALE_DETAIL
    WHERE SALE_ID = P_SALE_ID;


    IF V_COUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20211,
            'Sale has no items.'
        );
    END IF;


    SELECT SUM(SUBTOTAL)
    INTO V_SUBTOTAL
    FROM SALE_DETAIL
    WHERE SALE_ID = P_SALE_ID;


    IF V_ORDER_DISCOUNT > V_SUBTOTAL THEN
        RAISE_APPLICATION_ERROR(
            -20212,
            'Order discount exceeds subtotal.'
        );
    END IF;


    V_GRAND_TOTAL :=
        V_SUBTOTAL - V_ORDER_DISCOUNT;


    FOR R IN (
        SELECT
            VARIANT_ID,
            QUANTITY
        FROM SALE_DETAIL
        WHERE SALE_ID = P_SALE_ID
    )
    LOOP

        PKG_INVENTORY.REDUCE_STOCK(
            P_VARIANT_ID     => R.VARIANT_ID,
            P_QUANTITY       => R.QUANTITY,
            P_REFERENCE_TYPE => 'SALE',
            P_REFERENCE_ID   => P_SALE_ID,
            P_NOTE           => 'Sale completed'
        );

    END LOOP;


    UPDATE SALE
    SET
        SUBTOTAL = V_SUBTOTAL,
        GRAND_TOTAL = V_GRAND_TOTAL,
        STATUS = 'COMPLETED'
    WHERE SALE_ID = P_SALE_ID;

END;
