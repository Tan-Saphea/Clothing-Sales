    V_STATUS VARCHAR2(20);
    V_PRICE NUMBER;
    V_GROSS NUMBER;
    V_COUNT NUMBER;
BEGIN

    IF P_QUANTITY <= 0 THEN
        RAISE_APPLICATION_ERROR(
            -20202,
            'Sale quantity must be greater than zero.'
        );
    END IF;


    IF P_LINE_DISCOUNT < 0 THEN
        RAISE_APPLICATION_ERROR(
            -20203,
            'Line discount cannot be negative.'
        );
    END IF;


    BEGIN

        SELECT STATUS
        INTO V_STATUS
        FROM SALE
        WHERE SALE_ID = P_SALE_ID
