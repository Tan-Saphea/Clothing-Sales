    ---------------------------------------------------------
    -- GET STOCK
    ---------------------------------------------------------
    FUNCTION GET_STOCK (
        P_VARIANT_ID NUMBER
    )
    RETURN NUMBER
    IS
        V_STOCK NUMBER;
    BEGIN

        SELECT STOCK_QTY
        INTO V_STOCK
        FROM PRODUCT_VARIANT
        WHERE VARIANT_ID = P_VARIANT_ID;

        RETURN V_STOCK;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                -20001,
                'Product variant does not exist.'
            );
    END GET_STOCK;



    ---------------------------------------------------------
    -- ADD STOCK
    ---------------------------------------------------------
    PROCEDURE ADD_STOCK (
        P_VARIANT_ID     NUMBER,
        P_QUANTITY       NUMBER,
        P_REFERENCE_TYPE VARCHAR2,
        P_REFERENCE_ID   NUMBER,
        P_NOTE           VARCHAR2
    )
    IS
    BEGIN

        IF P_QUANTITY <= 0 THEN
            RAISE_APPLICATION_ERROR(
                -20002,
                'Quantity must be greater than zero.'
            );
        END IF;


        IF P_REFERENCE_TYPE IS NULL
           OR UPPER(P_REFERENCE_TYPE) NOT IN (
               'PURCHASE',
               'SALE',
               'RETURN',
               'ADJUSTMENT',
               'OPENING'
           )
        THEN
            RAISE_APPLICATION_ERROR(
                -20003,
                'Invalid stock reference type.'
            );
        END IF;


        UPDATE PRODUCT_VARIANT
        SET
            STOCK_QTY = STOCK_QTY + P_QUANTITY,
            UPDATED_AT = SYSTIMESTAMP
        WHERE VARIANT_ID = P_VARIANT_ID;


        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(
                -20004,
                'Product variant does not exist.'
            );
        END IF;


        INSERT INTO STOCK_MOVEMENT (
            VARIANT_ID,
            MOVEMENT_TYPE,
            REFERENCE_TYPE,
            REFERENCE_ID,
            QUANTITY,
            NOTE
        )
        VALUES (
            P_VARIANT_ID,
            'IN',
            UPPER(P_REFERENCE_TYPE),
            P_REFERENCE_ID,
            P_QUANTITY,
            P_NOTE
        );

    END ADD_STOCK;



