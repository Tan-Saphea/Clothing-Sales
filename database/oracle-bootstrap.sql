  CREATE OR REPLACE EDITIONABLE PROCEDURE "SP_ADD_SALE_ITEM" (
    P_SALE_ID       IN NUMBER,
    P_VARIANT_ID    IN NUMBER,
    P_QUANTITY      IN NUMBER,
    P_UNIT_PRICE    IN NUMBER DEFAULT NULL,
    P_LINE_DISCOUNT IN NUMBER DEFAULT 0
)
