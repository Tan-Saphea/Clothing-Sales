               'PURCHASE',
               'SALE',
               'RETURN',
               'ADJUSTMENT',
               'OPENING'
           )
        THEN
            RAISE_APPLICATION_ERROR(
                -20006,
                'Invalid stock reference type.'
            );
        END IF;


        BEGIN
            SELECT STOCK_QTY
            INTO V_STOCK
            FROM PRODUCT_VARIANT
            WHERE VARIANT_ID = P_VARIANT_ID
            FOR UPDATE;

        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(
                    -20007,
                    'Product variant does not exist.'
                );
        END;


        IF V_STOCK < P_QUANTITY THEN
            RAISE_APPLICATION_ERROR(
                -20008,
                'Insufficient stock.'
            );
        END IF;


        UPDATE PRODUCT_VARIANT
        SET
            STOCK_QTY = STOCK_QTY - P_QUANTITY,
            UPDATED_AT = SYSTIMESTAMP
        WHERE VARIANT_ID = P_VARIANT_ID;


        INSERT INTO STOCK_MOVEMENT (
            VARIANT_ID,
            MOVEMENT_TYPE,
            REFERENCE_TYPE,
            REFERENCE_ID,
            QUANTITY,
            NOTE
        )
        VALUES (
            P_VARIANT_ID,
            'OUT',
            UPPER(P_REFERENCE_TYPE),
            P_REFERENCE_ID,
            P_QUANTITY,
            P_NOTE
        );

    END REDUCE_STOCK;



    ---------------------------------------------------------
    -- ADJUST STOCK
    ---------------------------------------------------------
    PROCEDURE ADJUST_STOCK (
        P_VARIANT_ID   NUMBER,
        P_NEW_QUANTITY NUMBER,
        P_NOTE         VARCHAR2
    )
    IS
        V_CURRENT NUMBER;
        V_DIFF NUMBER;
    BEGIN

        IF P_NEW_QUANTITY < 0 THEN
            RAISE_APPLICATION_ERROR(
                -20009,
                'New stock quantity cannot be negative.'
            );
        END IF;


        BEGIN

            SELECT STOCK_QTY
            INTO V_CURRENT
            FROM PRODUCT_VARIANT
            WHERE VARIANT_ID = P_VARIANT_ID
            FOR UPDATE;

        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(
                    -20010,
                    'Product variant does not exist.'
                );
        END;


        IF P_NEW_QUANTITY > V_CURRENT THEN

            V_DIFF := P_NEW_QUANTITY - V_CURRENT;

            UPDATE PRODUCT_VARIANT
            SET
                STOCK_QTY = P_NEW_QUANTITY,
                UPDATED_AT = SYSTIMESTAMP
            WHERE VARIANT_ID = P_VARIANT_ID;


            INSERT INTO STOCK_MOVEMENT (
                VARIANT_ID,
                MOVEMENT_TYPE,
                REFERENCE_TYPE,
                REFERENCE_ID,
                QUANTITY,
                NOTE
            )
            VALUES (
                P_VARIANT_ID,
                'IN',
                'ADJUSTMENT',
                NULL,
                V_DIFF,
                P_NOTE
            );


        ELSIF P_NEW_QUANTITY < V_CURRENT THEN

            V_DIFF := V_CURRENT - P_NEW_QUANTITY;

            UPDATE PRODUCT_VARIANT
            SET
                STOCK_QTY = P_NEW_QUANTITY,
                UPDATED_AT = SYSTIMESTAMP
            WHERE VARIANT_ID = P_VARIANT_ID;


            INSERT INTO STOCK_MOVEMENT (
                VARIANT_ID,
                MOVEMENT_TYPE,
                REFERENCE_TYPE,
                REFERENCE_ID,
                QUANTITY,
                NOTE
            )
            VALUES (
                P_VARIANT_ID,
                'OUT',
                'ADJUSTMENT',
                NULL,
                V_DIFF,
                P_NOTE
            );

        END IF;

    END ADJUST_STOCK;


END PKG_INVENTORY;
