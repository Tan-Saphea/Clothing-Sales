  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_PRODUCT_STOCK" ("VARIANT_ID", "PRODUCT_ID", "PRODUCT_NAME", "CATEGORY_NAME", "SIZE_NAME", "COLOR_NAME", "SKU", "COST_PRICE", "SALE_PRICE", "STOCK_QTY", "STOCK_COST_VALUE", "STOCK_SALE_VALUE", "IS_ACTIVE") AS 
  SELECT
    PV.VARIANT_ID,
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    C.CATEGORY_NAME,
    PS.SIZE_NAME,
    CO.COLOR_NAME,
    PV.SKU,
    PV.COST_PRICE,
    PV.SALE_PRICE,
    PV.STOCK_QTY,
    PV.STOCK_QTY * PV.COST_PRICE AS STOCK_COST_VALUE,
    PV.STOCK_QTY * PV.SALE_PRICE AS STOCK_SALE_VALUE,
    P.IS_ACTIVE
FROM PRODUCT_VARIANT PV
JOIN PRODUCT P
    ON PV.PRODUCT_ID = P.PRODUCT_ID
JOIN CATEGORY C
    ON P.CATEGORY_ID = C.CATEGORY_ID
JOIN PRODUCT_SIZE PS
    ON PV.SIZE_ID = PS.SIZE_ID
JOIN COLOR CO
    ON PV.COLOR_ID = CO.COLOR_ID;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_LOW_STOCK" ("VARIANT_ID", "PRODUCT_NAME", "SIZE_NAME", "COLOR_NAME", "SKU", "STOCK_QTY", "SALE_PRICE") AS 
  SELECT
    PV.VARIANT_ID,
    P.PRODUCT_NAME,
    PS.SIZE_NAME,
    CO.COLOR_NAME,
    PV.SKU,
    PV.STOCK_QTY,
    PV.SALE_PRICE
FROM PRODUCT_VARIANT PV
JOIN PRODUCT P
    ON PV.PRODUCT_ID = P.PRODUCT_ID
JOIN PRODUCT_SIZE PS
    ON PV.SIZE_ID = PS.SIZE_ID
JOIN COLOR CO
    ON PV.COLOR_ID = CO.COLOR_ID
WHERE PV.STOCK_QTY <= 5
AND P.IS_ACTIVE = 'Y';

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_STOCK_MOVEMENT" ("MOVEMENT_ID", "MOVEMENT_DATE", "PRODUCT_NAME", "SIZE_NAME", "COLOR_NAME", "SKU", "MOVEMENT_TYPE", "REFERENCE_TYPE", "REFERENCE_ID", "QUANTITY", "SIGNED_QUANTITY", "NOTE") AS 
  SELECT
    SM.MOVEMENT_ID,
    SM.MOVEMENT_DATE,
    P.PRODUCT_NAME,
    PS.SIZE_NAME,
    CO.COLOR_NAME,
    PV.SKU,

    SM.MOVEMENT_TYPE,
    SM.REFERENCE_TYPE,
    SM.REFERENCE_ID,

    SM.QUANTITY,

    CASE
        WHEN SM.MOVEMENT_TYPE = 'IN'
            THEN SM.QUANTITY
        ELSE -SM.QUANTITY
    END AS SIGNED_QUANTITY,

    SM.NOTE

FROM STOCK_MOVEMENT SM

JOIN PRODUCT_VARIANT PV
    ON SM.VARIANT_ID = PV.VARIANT_ID

JOIN PRODUCT P
    ON PV.PRODUCT_ID = P.PRODUCT_ID

JOIN PRODUCT_SIZE PS
    ON PV.SIZE_ID = PS.SIZE_ID

JOIN COLOR CO
    ON PV.COLOR_ID = CO.COLOR_ID;
