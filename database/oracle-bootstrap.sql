  CREATE OR REPLACE EDITIONABLE PROCEDURE "SP_RECORD_PAYMENT" (
    P_SALE_ID        IN NUMBER,
    P_AMOUNT         IN NUMBER,
    P_PAYMENT_METHOD IN VARCHAR2,
    P_REFERENCE_NO   IN VARCHAR2 DEFAULT NULL
)
AS
    V_STATUS VARCHAR2(20);
    V_TOTAL NUMBER;
    V_PAID NUMBER;
BEGIN

    IF P_AMOUNT <= 0 THEN
        RAISE_APPLICATION_ERROR(
            -20301,
            'Payment amount must be greater than zero.'
        );
    END IF;


    BEGIN

        SELECT
            STATUS,
            GRAND_TOTAL
        INTO
            V_STATUS,
            V_TOTAL
        FROM SALE
        WHERE SALE_ID = P_SALE_ID
        FOR UPDATE;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(
                -20302,
                'Sale does not exist.'
            );
    END;


    IF V_STATUS <> 'COMPLETED' THEN
        RAISE_APPLICATION_ERROR(
            -20303,
            'Only completed sales can receive payment.'
        );
    END IF;


    SELECT NVL(SUM(AMOUNT), 0)
    INTO V_PAID
    FROM PAYMENT
    WHERE SALE_ID = P_SALE_ID
    AND PAYMENT_STATUS = 'PAID';


    IF V_PAID + P_AMOUNT > V_TOTAL THEN
        RAISE_APPLICATION_ERROR(
            -20304,
            'Payment exceeds sale balance.'
        );
    END IF;


    INSERT INTO PAYMENT (
        SALE_ID,
        AMOUNT,
        PAYMENT_METHOD,
        PAYMENT_STATUS,
        REFERENCE_NO
    )
    VALUES (
        P_SALE_ID,
        P_AMOUNT,
        UPPER(P_PAYMENT_METHOD),
        'PAID',
        P_REFERENCE_NO
    );

END;
